-- Generates test/sort_cases.h with real Lua 5.1: what table.sort and tostring give, for core_test.c to compare.
-- Run: /root/lua51/lua test/sort_gen.lua > test/sort_cases.h   (core_test.sh does it when the interpreter is there)

-- The comparators, mirrored one by one in core_test.c (same index). 3 and 4 are not valid orders on purpose.
local cmps = {
    [0] = function(a, b) return a < b end,
    [1] = function(a, b) return a > b end,
    [2] = function(a, b) return a % 7 < b % 7 end,
    [3] = function(a, b) return a <= b end,
    [4] = function(a, b) return (a * 7 + b * 3) % 5 < 2 end,
    [5] = function(a, b) return math.floor(a / 10) < math.floor(b / 10) end,
}

math.randomseed(20240220)
local out, ncases, dropped = {}, 0, 0
local per_cmp = {}
local function emit(s) out[#out + 1] = s end
local function list(t) return #t == 0 and "0" or table.concat(t, ",") end

local rows = {}
for _, size in ipairs({0, 1, 2, 3, 4, 5, 7, 10, 16, 33, 50, 100, 300}) do
    for _, range in ipairs({3, 20, 1000}) do
        for c = 0, 5 do
            for rep = 1, 2 do
                local input, t = {}, {}
                for i = 1, size do input[i] = math.random(0, range); t[i] = input[i] end
                local calls, trace = 0, 0
                -- the trace pins the sequence of comparator calls, not just the result
                local ok = pcall(table.sort, t, function(a, b)
                    calls = calls + 1
                    trace = (trace * 31 + a * 7 + b) % 1000003
                    return cmps[c](a, b)
                end)
                if ok then -- an invalid order can make Lua raise an error: those arrays are not cases
                    emit(("static const double sc%d_in[] = {%s};"):format(ncases, list(input)))
                    emit(("static const double sc%d_out[] = {%s};"):format(ncases, list(t)))
                    rows[#rows + 1] = ("    {%d, %d, sc%d_in, sc%d_out, %d, %d},"):format(c, size, ncases, ncases, calls, trace)
                    ncases = ncases + 1
                    per_cmp[c] = (per_cmp[c] or 0) + 1
                else
                    dropped = dropped + 1
                end
            end
        end
    end
end

print("// Generated by test/sort_gen.lua with Lua 5.1.5: do not edit.")
print(("// %d cases (%d arrays dropped because Lua raised an error); per comparator: %d %d %d %d %d %d"):format(
    ncases, dropped, per_cmp[0], per_cmp[1], per_cmp[2], per_cmp[3], per_cmp[4], per_cmp[5]))
print("typedef struct { int cmp, n; const double *in, *out; double calls, trace; } SortCase;")
print(table.concat(out, "\n"))
print("static const SortCase sort_cases[] = {")
print(table.concat(rows, "\n"))
print("};")

-- strings with the default comparator
local words = {"pear", "Apple", "fig", "apple", "", "banana", "fig", "Zed", "a", "ab", "aa", "kiwi", "10", "9", "cherry"}
local sorted = {}
for i, w in ipairs(words) do sorted[i] = w end
table.sort(sorted)
local function q(t) local r = {} for i, w in ipairs(t) do r[i] = ("%q"):format(w) end return table.concat(r, ",") end
print(("static const char *const sort_words_in[] = {%s};"):format(q(words)))
print(("static const char *const sort_words_out[] = {%s};"):format(q(sorted)))

